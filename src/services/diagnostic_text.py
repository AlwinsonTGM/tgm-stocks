def diagnostic_text(language: Any, key: str, **kwargs: Any) -> str:
    """Return a localized diagnostic string, falling back to Chinese."""
    lang = normalize_diagnostic_language(language)
    template = _MESSAGES.get(lang, {}).get(key)
    if template is None:
        template = _MESSAGES[DEFAULT_DIAGNOSTIC_LANGUAGE].get(key, key)
    if not kwargs:
        return template
    try:
        return template.format(**kwargs)
    except (KeyError, IndexError):
        return template


def data_type_label(data_type: Any, language: Any = None) -> str:
    """Return a localized label for a provider data type."""
    key = str(data_type or "").strip()
    lang = normalize_diagnostic_language(language)
    table = _DATA_TYPE_LABELS.get(lang) or _DATA_TYPE_LABELS[DEFAULT_DIAGNOSTIC_LANGUAGE]
    return table.get(key, key or "provider")


def flow_lanes(language: Any = None) -> List[Dict[str, Any]]:
    """Return the run-flow lane definitions in the requested language."""
    lang = normalize_diagnostic_language(language)
    labels = _LANE_LABELS.get(lang) or _LANE_LABELS[DEFAULT_DIAGNOSTIC_LANGUAGE]
    return [
        {"id": lane_id, "label": labels.get(lane_id, lane_id), "order": order}
        for lane_id, order in _LANE_ORDER
    ]
