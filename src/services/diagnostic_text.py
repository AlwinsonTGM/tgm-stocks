DEFAULT_DIAGNOSTIC_LANGUAGE = "zh"
SUPPORTED_DIAGNOSTIC_LANGUAGES = ("zh", "en", "ko")

_LANGUAGE_ALIASES = {
    "zh": "zh",
    "zh-cn": "zh",
    "zh-hans": "zh",
    "zh-hant": "zh",
    "cn": "zh",
    "chinese": "zh",
    "en": "en",
    "en-us": "en",
    "en-gb": "en",
    "english": "en",
    "ko": "ko",
    "ko-kr": "ko",
    "kr": "ko",
    "korean": "ko",
}


def normalize_diagnostic_language(
    value: Any,
    default: str = DEFAULT_DIAGNOSTIC_LANGUAGE,
) -> str:
    """Normalize a report language into a supported diagnostic language."""
    if isinstance(value, str):
        key = value.strip().lower().replace("_", "-")
        if key in _LANGUAGE_ALIASES:
            return _LANGUAGE_ALIASES[key]
        base = key.split("-", 1)[0]
        if base in _LANGUAGE_ALIASES:
            return _LANGUAGE_ALIASES[base]
    if default in SUPPORTED_DIAGNOSTIC_LANGUAGES:
        return default
    return DEFAULT_DIAGNOSTIC_LANGUAGE


